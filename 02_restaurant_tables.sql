USE QL_KhachSan_NhaHang;
GO
SET XACT_ABORT ON;
BEGIN TRAN;
CREATE TABLE dbo.MON_AN (
 MaMon INT IDENTITY PRIMARY KEY,
 TenMon NVARCHAR(100) NOT NULL UNIQUE CHECK(LEN(LTRIM(RTRIM(TenMon)))>0),
 DonGia DECIMAL(12,0) NOT NULL CHECK(DonGia>0),
 LoaiMon NVARCHAR(50) NOT NULL CHECK(LEN(LTRIM(RTRIM(LoaiMon)))>0),
 TrangThai NVARCHAR(20) NOT NULL DEFAULT N'Còn bán' CHECK(TrangThai IN(N'Còn bán',N'Ngừng bán'))
);
CREATE TABLE dbo.PHIEU_GOI_MON (
 MaGoiMon INT IDENTITY PRIMARY KEY,
 MaPhieu INT NOT NULL REFERENCES dbo.PHIEU_THUE_PHONG(MaPhieu),
 MaNV INT NOT NULL REFERENCES dbo.NHAN_VIEN(MaNV),
 NgayGoi DATETIME NOT NULL DEFAULT GETDATE()
);
CREATE TABLE dbo.CHI_TIET_GOI_MON (
 MaGoiMon INT NOT NULL REFERENCES dbo.PHIEU_GOI_MON(MaGoiMon),
 MaMon INT NOT NULL REFERENCES dbo.MON_AN(MaMon),
 SoLuong INT NOT NULL CHECK(SoLuong>0),
 DonGia DECIMAL(12,0) NOT NULL CHECK(DonGia>0),
 PRIMARY KEY(MaGoiMon,MaMon)
);
CREATE TABLE dbo.HOA_DON (
 MaHD INT IDENTITY PRIMARY KEY,
 MaPhieu INT NOT NULL UNIQUE REFERENCES dbo.PHIEU_THUE_PHONG(MaPhieu),
 MaNV INT NOT NULL REFERENCES dbo.NHAN_VIEN(MaNV),
 NgayLap DATETIME NOT NULL DEFAULT GETDATE(),
 TongTien DECIMAL(19,0) NOT NULL DEFAULT 0 CHECK(TongTien>=0),
 TrangThai NVARCHAR(20) NOT NULL DEFAULT N'Chưa thanh toán'
 CHECK(TrangThai IN(N'Chưa thanh toán',N'Đã thanh toán'))
);
CREATE TABLE dbo.CHI_TIET_HOA_DON (
 MaCT INT IDENTITY PRIMARY KEY,
 MaHD INT NOT NULL REFERENCES dbo.HOA_DON(MaHD),
 LoaiDong NVARCHAR(10) NOT NULL CHECK(LoaiDong IN(N'Phòng',N'Món')),
 NoiDung NVARCHAR(200) NOT NULL CHECK(LEN(LTRIM(RTRIM(NoiDung)))>0),
 SoLuong INT NOT NULL CHECK(SoLuong>0),
 DonGia DECIMAL(12,0) NOT NULL CHECK(DonGia>0),
 ThanhTien AS (CONVERT(DECIMAL(19,0),CONVERT(DECIMAL(19,0),SoLuong)*DonGia)) PERSISTED
);
CREATE INDEX IX_PGM_MaPhieu ON dbo.PHIEU_GOI_MON(MaPhieu);
CREATE INDEX IX_PGM_MaNV ON dbo.PHIEU_GOI_MON(MaNV);
CREATE INDEX IX_CTGM_MaMon ON dbo.CHI_TIET_GOI_MON(MaMon);
CREATE INDEX IX_HD_NgayLap ON dbo.HOA_DON(NgayLap) INCLUDE(TongTien,TrangThai);
CREATE INDEX IX_CTHD_MaHD ON dbo.CHI_TIET_HOA_DON(MaHD);
COMMIT;
GO
